#!/usr/bin/env bun
// Agent-status dashboard: every live agent log, grouped by status.
//   dashboard.ts           print the groups to the terminal
//   dashboard.ts --write   also regenerate dashboard/agent-status.md (no frontmatter; generated)
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { pc } from "./cli-colors.ts";
import { runMain, toPosix } from "./config.ts";
import { extractField, readFrontmatterFile } from "./frontmatter.ts";
import { mdLink } from "./links.ts";
import { findAgentLogs } from "./validate-logs.ts";

export const ARTIFACT = "dashboard/agent-status.md";
const GENERATED_HEADER = "<!-- generated by scripts/dashboard.ts — regenerate, don't hand-edit -->";

export interface TaskLog {
  path: string; // vault-relative, forward slashes
  agent: string;
  status: string;
  priority: string;
  date: string;
  task: string;
  verified: boolean;
}

/** Groups in display order; "unverified" is completed logs a human has not yet checked. */
const GROUPS: { title: string; pick: (l: TaskLog) => boolean }[] = [
  { title: "Needs you (awaiting approval or blocked)", pick: (l) => l.status === "awaiting-approval" || l.status === "blocked" },
  { title: "Errors", pick: (l) => l.status === "error" },
  { title: "Active", pick: (l) => l.status === "active" },
  { title: "Completed, unverified", pick: (l) => l.status === "completed" && !l.verified },
  { title: "Completed, verified", pick: (l) => l.status === "completed" && l.verified },
];

const PRIO: Record<string, number> = { high: 0, medium: 1, low: 2 };
const byPrioThenDate = (a: TaskLog, b: TaskLog) =>
  (PRIO[a.priority] ?? 9) - (PRIO[b.priority] ?? 9) || b.date.localeCompare(a.date) || a.path.localeCompare(b.path);

export function collectLogs(vaultRoot: string): TaskLog[] {
  const out: TaskLog[] = [];
  for (const abs of findAgentLogs(vaultRoot)) {
    const f = readFrontmatterFile(abs);
    if (!f) continue;
    const get = (k: string) => extractField(f.fm, k) ?? "";
    out.push({
      path: toPosix(relative(vaultRoot, abs)),
      agent: get("agent"),
      status: get("status"),
      priority: get("priority"),
      date: get("date"),
      task: get("task"),
      verified: get("verified") === "true",
    });
  }
  return out.sort(byPrioThenDate);
}

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

export function renderMarkdown(all: TaskLog[]): string {
  const parts = [GENERATED_HEADER, "", "# Agent Status", "", `${all.length} live agent log(s). Regenerate with \`bun run dashboard --write\`.`];
  for (const g of GROUPS) {
    const rows = all.filter(g.pick);
    parts.push("", `## ${g.title} (${rows.length})`, "");
    if (!rows.length) { parts.push("_(none)_"); continue; }
    parts.push("| Date | Priority | Agent | Task |", "|---|---|---|---|");
    for (const l of rows)
      parts.push(`| ${l.date} | ${l.priority} | ${cell(l.agent)} | ${mdLink(l.task.replace(/\s+/g, " ").trim() || l.path, ARTIFACT, l.path, null, true)} |`);
  }
  return parts.join("\n") + "\n";
}

export function render(all: TaskLog[]): string {
  const lines: string[] = [];
  for (const g of GROUPS) {
    const rows = all.filter(g.pick);
    if (!rows.length) continue;
    lines.push(pc.bold(`${g.title} (${rows.length})`));
    for (const l of rows) lines.push(`  ${pc.dim(l.date)}  ${l.priority.padEnd(6)}  ${l.task}  ${pc.cyan(l.path)}`);
    lines.push("");
  }
  return lines.length ? lines.join("\n") : "No live agent logs.\n";
}

function main() {
  const vaultRoot = resolve(import.meta.dir, "..");
  const logs = collectLogs(vaultRoot);
  console.log(render(logs).trimEnd());
  if (process.argv.includes("--write")) {
    const out = join(vaultRoot, ARTIFACT);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, renderMarkdown(logs), "utf8");
    console.log(`wrote ${ARTIFACT}`);
  }
}

if (import.meta.main) runMain(main);
